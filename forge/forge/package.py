"""Assemble a FiveM resource from the Sollumz export.

    <resource>/
      fxmanifest.lua      this_is_a_map + DLC_ITYP_REQUEST for our .ytyp
      client.lua          /<prefix> teleports to the front door, /vm_here prints a placement
      stream/             .ydr .ybn .ytd .ytyp .ymap (native binary export)

Natives used were checked against the FiveM native index (muto-atlas fivem-natives):
SetEntityCoords(entity, x, y, z, alive, deadFlag, ragdollFlag, clearArea),
GetGroundZFor3dCoord(x, y, z, includeWater) -> found, z   (NOT GetGroundZFor_3dCoord),
GetEntityCoords(entity, alive), GetEntityHeading, SetEntityHeading, RequestCollisionAtCoord,
RegisterCommand(name, handler, restricted), PlayerPedId, Wait.
"""

from __future__ import annotations

import json
import math
import shutil
from pathlib import Path

STREAM_EXT = (".ydr", ".ybn", ".ytd", ".ytyp", ".ymap", ".ydd", ".yft")

FXMANIFEST = """fx_version 'cerulean'
game 'gta5'
lua54 'yes'

name '{name}'
description '{title}: generated by viewmaxxing MLO Forge'
version '{version}'

this_is_a_map 'yes'

data_file 'DLC_ITYP_REQUEST' 'stream/{ytyp}'

client_script 'client.lua'
"""

CLIENT = """-- {title}: test helpers (generated)
local ENTRANCE = vector3({ex:.3f}, {ey:.3f}, {ez:.3f})
local ENTRANCE_HEADING = {eh:.1f}

RegisterCommand('{cmd}', function()
    local ped = PlayerPedId()
    RequestCollisionAtCoord(ENTRANCE.x, ENTRANCE.y, ENTRANCE.z)
    SetEntityCoords(ped, ENTRANCE.x, ENTRANCE.y, ENTRANCE.z, false, false, false, true)
    SetEntityHeading(ped, ENTRANCE_HEADING)
    print('[{cmd}] teleported to the front door of {title}')
end, false)

-- Stand where you want the building's front-centre and face the street, then run /vm_here.
-- Paste the printed line into the spec's "placement" and rebuild.
RegisterCommand('vm_here', function()
    local ped = PlayerPedId()
    local p = GetEntityCoords(ped, true)
    local found, groundZ = GetGroundZFor3dCoord(p.x, p.y, p.z, false)
    local z = found and groundZ or (p.z - 1.0)
    local heading = GetEntityHeading(ped)
    print(string.format('"placement": {{"position": [%.2f, %.2f, %.2f], "heading_deg": %.1f, "anchor": "front_centre"}}',
        p.x, p.y, z, heading))
end, false)
"""


def rotate(heading_deg: float, x: float, y: float):
    a = math.radians(heading_deg)
    return x * math.cos(a) - y * math.sin(a), x * math.sin(a) + y * math.cos(a)


def make_resource(model: dict, export_dir: Path, out_dir: Path, title: str, version: str = "0.1.0") -> Path:
    export_dir, out_dir = Path(export_dir), Path(out_dir)
    name = f"{model['prefix']}_{model['id'].split('_')[-1]}"
    res = out_dir / name
    if res.exists():
        shutil.rmtree(res)
    (res / "stream").mkdir(parents=True)

    found = [p for p in export_dir.rglob("*") if p.is_file() and p.suffix in STREAM_EXT]
    if not found:
        raise SystemExit(
            f"No native GTA files in {export_dir}. Export used CodeWalker XML: install PyMateria in "
            "Sollumz (Preferences → Dependencies) and rebuild, or convert the .xml files with CodeWalker."
        )
    names = [p.name for p in found]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:   # FiveM silently ignores one of two same-named stream files (muto-atlas §6)
        raise SystemExit(f"duplicate stream file names: {sorted(dupes)}")
    for p in found:
        shutil.copy2(p, res / "stream" / p.name)
    ytyp = next((n for n in names if n.endswith(".ytyp")), None)
    if ytyp is None:
        raise SystemExit("no .ytyp in the export")

    place = model["placement"]
    px, py, pz = place["position"]
    heading = place.get("heading_deg", 0.0)
    # front door: centre of the front wall, 2 m outside (building faces -Y locally)
    entry = next((p for p in model["mlo"]["portals"] if p.get("kind") == "entry"), None)
    if entry:
        ex_local = sum(c[0] for c in entry["corners"]) / 4
        ey_local = min(c[1] for c in entry["corners"]) - 2.0
    else:
        ex_local, ey_local = 0.0, -8.0
    dx, dy = rotate(heading, ex_local, ey_local)
    (res / "fxmanifest.lua").write_text(FXMANIFEST.format(name=name, title=title, version=version, ytyp=ytyp))
    (res / "client.lua").write_text(CLIENT.format(
        title=title, cmd=model["prefix"], ex=px + dx, ey=py + dy, ez=pz + 0.5, eh=(heading) % 360.0))
    (res / "build_info.json").write_text(json.dumps({"files": sorted(names), "placement": place}, indent=1))
    return res
